use std::{
    collections::BTreeSet,
    error::Error,
    fmt,
    io::{self, Write},
};

use crate::{c_func::CFunction, inst_translator::CodeLine};

pub struct CodeFile {
    funcs: BTreeSet<CFunction>,
}

impl CodeFile {
    fn prologue() -> Vec<CodeLine> {
        let mut lines = Vec::new();

        lines.push(CodeLine::new(0, "// Generated by bf-codegen.".into()));

        lines.push(CodeLine::new_empty_line());

        lines.push(CodeLine::new(0, "#include <bfni.h>".into()));

        lines
    }
}

impl CodeFile {
    pub fn new() -> Self {
        Self {
            funcs: BTreeSet::new(),
        }
    }
}

impl Default for CodeFile {
    fn default() -> Self {
        Self::new()
    }
}

#[derive(Debug, PartialEq, Eq)]
pub enum AddFuncError {
    DuplicateFunctionName(String),
}

impl fmt::Display for AddFuncError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::DuplicateFunctionName(name) => {
                write!(f, "duplicate generated function name: {name}")
            }
        }
    }
}

impl Error for AddFuncError {}

impl CodeFile {
    pub fn add_bf_func(&mut self, func: CFunction) -> Result<(), AddFuncError> {
        let name = func.name.clone();

        if self.funcs.insert(func) {
            Ok(())
        } else {
            Err(AddFuncError::DuplicateFunctionName(name))
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{CompileOptions, compile_function};

    #[test]
    fn functions_are_emitted_in_name_order() {
        let options = CompileOptions::default();
        let world = compile_function("+", "world", options).unwrap();
        let hello = compile_function("-", "hello", options).unwrap();

        let mut file = CodeFile::new();
        file.add_bf_func(world).unwrap();
        file.add_bf_func(hello).unwrap();

        let mut output = Vec::new();
        file.write_to(&mut output).unwrap();
        let output = String::from_utf8(output).unwrap();

        assert!(output.find("hello(").unwrap() < output.find("world(").unwrap());
    }

    #[test]
    fn duplicate_function_names_are_rejected() {
        let options = CompileOptions::default();
        let first = compile_function("+", "same_name", options).unwrap();
        let second = compile_function("-", "same_name", options).unwrap();

        let mut file = CodeFile::new();
        file.add_bf_func(first).unwrap();

        assert_eq!(
            file.add_bf_func(second),
            Err(AddFuncError::DuplicateFunctionName("same_name".into()))
        );
    }
}

impl CodeFile {
    pub fn write_to(self, wr: &mut dyn Write) -> io::Result<()> {
        let mut lines = Vec::new();

        lines.append(&mut Self::prologue());

        for mut func in self.funcs {
            lines.push(CodeLine::new_empty_line());
            lines.append(&mut func.lines);
        }

        for line in lines {
            writeln!(wr, "{}", line.as_string())?;
        }

        Ok(())
    }
}
